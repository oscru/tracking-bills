/** A currency's name in the current language — "peso mexicano" / "Mexican Peso". */
export function currencyName(currency: CurrencyMeta): string {
  return currentLanguage() === 'en'
    ? (CURRENCY_NAMES_EN[currency.code] ?? currency.name)
    : currency.name;
}

/** Looks up a currency's metadata by its ISO code, case-insensitive. */
export function findCurrency(code: string): CurrencyMeta | undefined {
  const upper = code.trim().toUpperCase();
  return CURRENCIES.find((c) => c.code === upper);
}
